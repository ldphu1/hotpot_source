
CREATE TRIGGER trg_gen_ma_nhan_vien
    ON nhan_vien
    AFTER INSERT
AS
BEGIN
SET NOCOUNT ON;
DECLARE @id BIGINT,@ma NVARCHAR(50);
DECLARE cur CURSOR FOR SELECT id FROM inserted;
OPEN cur;
FETCH NEXT FROM cur INTO @id;
WHILE @@FETCH_STATUS=0
BEGIN
WHILE 1=1
BEGIN
SET @ma='NV-'+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR)+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR);
IF NOT EXISTS(SELECT 1 FROM nhan_vien WHERE ma_nhan_vien=@ma) BREAK;
END
UPDATE nhan_vien SET ma_nhan_vien=@ma WHERE id=@id;
FETCH NEXT FROM cur INTO @id;
END
CLOSE cur;
DEALLOCATE cur;
END

