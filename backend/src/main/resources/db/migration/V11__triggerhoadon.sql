
CREATE TRIGGER trg_gen_ma_hoa_don
    ON hoa_don
    AFTER INSERT
AS
BEGIN
SET NOCOUNT ON;
DECLARE @id BIGINT,@ma NVARCHAR(50);
DECLARE cur CURSOR FOR SELECT id FROM inserted;
OPEN cur;
FETCH NEXT FROM cur INTO @id;
WHILE @@FETCH_STATUS=0
BEGIN
WHILE 1=1
BEGIN
SET @ma='HD-'+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR)+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR);
IF NOT EXISTS(SELECT 1 FROM hoa_don WHERE ma_hoa_don=@ma) BREAK;
END
UPDATE hoa_don SET ma_hoa_don=@ma WHERE id=@id;
FETCH NEXT FROM cur INTO @id;
END
CLOSE cur;
DEALLOCATE cur;
END
