CREATE TRIGGER trg_gen_ma_khach_hang
    ON khach_hang
    AFTER INSERT
AS
BEGIN
SET NOCOUNT ON;
DECLARE @id BIGINT,@ma NVARCHAR(50);
DECLARE cur CURSOR FOR SELECT id FROM inserted;
OPEN cur;
FETCH NEXT FROM cur INTO @id;
WHILE @@FETCH_STATUS=0
BEGIN
WHILE 1=1
BEGIN
SET @ma='KH-'+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR)+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR);
IF NOT EXISTS(SELECT 1 FROM khach_hang WHERE ma_khach_hang=@ma) BREAK;
END
UPDATE khach_hang SET ma_khach_hang=@ma WHERE id=@id;
FETCH NEXT FROM cur INTO @id;
END
CLOSE cur;
DEALLOCATE cur;
END

