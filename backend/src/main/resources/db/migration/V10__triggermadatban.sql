CREATE TRIGGER trg_gen_ma_dat_ban
    ON dat_ban
    AFTER INSERT
AS
BEGIN
SET NOCOUNT ON;
DECLARE @id BIGINT,@ma NVARCHAR(50);
DECLARE cur CURSOR FOR SELECT id FROM inserted;
OPEN cur;
FETCH NEXT FROM cur INTO @id;
WHILE @@FETCH_STATUS=0
BEGIN
WHILE 1=1
BEGIN
SET @ma='DB-'+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR)+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR);
IF NOT EXISTS(SELECT 1 FROM dat_ban WHERE ma_dat_ban=@ma) BREAK;
END
UPDATE dat_ban SET ma_dat_ban=@ma WHERE id=@id;
FETCH NEXT FROM cur INTO @id;
END
CLOSE cur;
DEALLOCATE cur;
END
