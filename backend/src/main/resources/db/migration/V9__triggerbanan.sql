CREATE TRIGGER trg_gen_ma_ban_an
    ON ban_an
    AFTER INSERT
AS
BEGIN
SET NOCOUNT ON;
DECLARE @id BIGINT,@ma NVARCHAR(50);
DECLARE cur CURSOR FOR SELECT id FROM inserted;
OPEN cur;
FETCH NEXT FROM cur INTO @id;
WHILE @@FETCH_STATUS=0
BEGIN
WHILE 1=1
BEGIN
SET @ma='BA-'+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR)+CHAR(65+ABS(CHECKSUM(NEWID()))%26)+CAST(ABS(CHECKSUM(NEWID()))%10 AS VARCHAR);
IF NOT EXISTS(SELECT 1 FROM ban_an WHERE ma_ban_an=@ma) BREAK;
END
UPDATE ban_an SET ma_ban_an=@ma WHERE id=@id;
FETCH NEXT FROM cur INTO @id;
END
CLOSE cur;
DEALLOCATE cur;
END


